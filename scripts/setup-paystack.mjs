#!/usr/bin/env node
/**
 * Creates a R500/month ZAR Paystack plan and writes .env.local.
 *
 * Usage:
 *   PAYSTACK_SECRET_KEY=sk_test_xxx node scripts/setup-paystack.mjs
 *   # or:
 *   npm run setup:paystack -- sk_test_xxx
 */

import { writeFileSync, existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

const MONTHLY_AMOUNT_CENTS = 500 * 100; // R500
const PLAN_NAME = "AI Fitness Coach — Monthly";
const ENV_PATH = resolve(process.cwd(), ".env.local");

const secretKey =
  process.argv[2]?.trim() ||
  process.env.PAYSTACK_SECRET_KEY?.trim() ||
  "";

if (!secretKey || !secretKey.startsWith("sk_")) {
  console.error(`
Missing Paystack secret key.

1. Open https://dashboard.paystack.com/#/settings/developer
2. Copy your Test Secret Key (sk_test_…)
3. Run:

   npm run setup:paystack -- sk_test_YOUR_KEY_HERE
`);
  process.exit(1);
}

async function createPlan() {
  const res = await fetch("https://api.paystack.co/plan", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${secretKey}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      name: PLAN_NAME,
      interval: "monthly",
      amount: MONTHLY_AMOUNT_CENTS,
      currency: "ZAR",
      description: "Full access after 7-day free trial",
    }),
  });

  const json = await res.json();
  if (!json.status || !json.data?.plan_code) {
    throw new Error(json.message || `Paystack plan create failed (${res.status})`);
  }
  return json.data;
}

function upsertEnvLocal(planCode) {
  const lines = [
    `# Generated by scripts/setup-paystack.mjs — do not commit`,
    `PAYSTACK_SECRET_KEY=${secretKey}`,
    `PAYSTACK_PLAN_CODE=${planCode}`,
    `NEXT_PUBLIC_SITE_URL=http://localhost:3000`,
    "",
  ];

  let existing = "";
  if (existsSync(ENV_PATH)) {
    existing = readFileSync(ENV_PATH, "utf8");
  }

  const keep = existing
    .split("\n")
    .filter(
      (line) =>
        line &&
        !line.startsWith("PAYSTACK_SECRET_KEY=") &&
        !line.startsWith("PAYSTACK_PLAN_CODE=") &&
        !line.startsWith("PAYSTACK_WEBHOOK_SECRET=") &&
        !line.startsWith("NEXT_PUBLIC_SITE_URL=") &&
        !line.startsWith("# Generated by scripts/setup-paystack")
    )
    .join("\n");

  const content = [...lines, keep ? keep + "\n" : ""].join("\n");
  writeFileSync(ENV_PATH, content, "utf8");
}

const plan = await createPlan();
upsertEnvLocal(plan.plan_code);

console.log(`
✅ Paystack plan created
   Name:     ${plan.name}
   Code:     ${plan.plan_code}
   Amount:   R${(plan.amount / 100).toFixed(0)} / ${plan.interval}
   Currency: ${plan.currency}

✅ Wrote ${ENV_PATH}

Next steps:
1. Restart the Next.js dev server so it picks up .env.local
2. In Paystack Dashboard → Settings → API Keys & Webhooks, add:
     https://YOUR_PRODUCTION_URL/api/paystack/webhook
3. On Netlify, set env vars:
     PAYSTACK_SECRET_KEY
     PAYSTACK_PLAN_CODE=${plan.plan_code}
     NEXT_PUBLIC_SITE_URL=https://YOUR_PRODUCTION_URL
`);
